// Exact directory names that mark everything beneath them, wherever they sit.
//
// `gpucache` is kept separate from `cache` on purpose. GPU, shader and compiled
// -code caches are machine-generated artifacts that every Chromium build
// regenerates on next launch. A directory merely called "Cache" is not that
// reliable -- it is whatever the application decided to put there.
const DIR_TAGS = new Map(
  Object.entries({
    temp: 'temp',
    tmp: 'temp',
    cache: 'cache',
    caches: 'cache',
    cachestorage: 'cache',
    cache_data: 'cache',
    'code cache': 'gpucache',
    gpucache: 'gpucache',
    dawncache: 'gpucache',
    dawngraphitecache: 'gpucache',
    dawnwebgpucache: 'gpucache',
    shadercache: 'gpucache',
    grshadercache: 'gpucache',
    crashdumps: 'crashdump',
    minidump: 'crashdump',
    crashpad: 'crashdump',
    logs: 'log',
    log: 'log',
    downloads: 'downloads',

    // Live application state. Nothing under these is ever disposable, whatever
    // it is named -- Chromium's Local Storage is a LevelDB whose write-ahead
    // log is literally called `000003.log`, which the log rule would otherwise
    // classify as an old log file and delete.
    'local storage': 'userdata',
    'session storage': 'userdata',
    indexeddb: 'userdata',
    leveldb: 'userdata',
    databases: 'userdata',
    'service worker': 'userdata',
    'local state': 'userdata',
    network: 'userdata',
    blob_storage: 'userdata',
    webstorage: 'userdata',
    'shared proto db': 'userdata',
  })
);

/** `https_example.com_0.indexeddb.leveldb` and friends. */
function isUserDataDirName(lower) {
  return lower.endsWith('.leveldb') || lower.endsWith('.indexeddb');
}

/**
 * Files an application's data directory is recognised by. Their presence means
 * "this folder is some program's live state", which switches the whole subtree
 * to the conservative rules.
 */
const APP_DATA_MARKERS = new Set([
  'local storage',
  'session storage',
  'indexeddb',
  'cookies',
  'cookies-journal',
  'preferences',
  'local state',
  'databases',
  'service worker',
  'leveldb',
  'network',
  'blob_storage',
  'webstorage',
  'settings.json',
  'config.json',
  'user.config',
]);

/**
 * Is this directory an application's data/profile folder?
 *
 * Recognised from the listing the walk already holds, so it costs no syscalls
 * and -- unlike a list of known apps -- it works for software that was never
 * heard of when this was written.
 */
function looksLikeAppData(entries) {
  for (const entry of entries) {
    const lower = entry.name.toLowerCase();
    if (APP_DATA_MARKERS.has(lower)) return true;
    if (entry.isFile() && (lower.endsWith('.sqlite') || lower.endsWith('.sqlite3'))) return true;
  }
  return false;
}

/**
 * Build-output names are far too generic to trust on their own -- `bin` is a
 * compiler's output directory inside a project and an installed program's
 * executables everywhere else. These only count when the *parent* directory
 * looks like a source project.
 */
const BUILD_DIR_NAMES = new Set(['obj', 'bin', 'dist', 'build', 'target', 'out']);

/** Files whose presence means "this directory is a source project". */
const PROJECT_MARKERS = new Set([
  'package.json',
  'cargo.toml',
  'go.mod',
  'pom.xml',
  'build.gradle',
  'build.gradle.kts',
  'makefile',
  'cmakelists.txt',
  'pyproject.toml',
  'composer.json',
  'gemfile',
  'build.sbt',
  'mix.exs',
]);

const PROJECT_MARKER_SUFFIXES = ['.csproj', '.sln', '.fsproj', '.vbproj', '.vcxproj'];

/**
 * Does this directory hold an installed application?
 *
 * This exists because of a real breakage: VS Code ships
 * `resources\app\package.json`, which made `looksLikeProject` true, which made
 * the sibling `out\` match the build-output rule -- so the editor's entire
 * compiled JavaScript was offered as "safe to delete". An application's
 * `out\` is its product, not rebuildable scratch.
 *
 * Detected from the listing the walk already has: an uninstaller, or an
 * executable sitting next to the `resources`/`locales`/`app` layout that
 * packaged apps use.
 *
 * @param {Array<{name: string, isFile: () => boolean, isDirectory: () => boolean}>} entries
 */
function looksLikeInstalledApp(entries) {
  let hasExecutable = false;
  let hasAppLayout = false;

  for (const entry of entries) {
    const lower = entry.name.toLowerCase();

    if (entry.isFile()) {
      if (/^unins.*\.exe$/.test(lower) || /^uninstall.*\.exe$/.test(lower)) return true;
      if (lower.endsWith('.exe')) hasExecutable = true;
      continue;
    }
    if (entry.isDirectory() && (lower === 'resources' || lower === 'locales')) {
      hasAppLayout = true;
    }
  }

  return hasExecutable && hasAppLayout;
}

/**
 * Does this directory listing belong to a source project? Called once per
 * directory with the entries the walk has already read, so it costs no extra
 * syscalls.
 *
 * @param {Array<{name: string, isFile: () => boolean}>} entries
 */
function looksLikeProject(entries) {
  for (const entry of entries) {
    if (!entry.isFile()) continue;
    const lower = entry.name.toLowerCase();
    if (PROJECT_MARKERS.has(lower)) return true;
    for (const suffix of PROJECT_MARKER_SUFFIXES) {
      if (lower.endsWith(suffix)) return true;
    }
  }
  return false;
}

/**
 * Tag for a directory. A tag, once applied, is inherited by every
 * subdirectory beneath it.
 *
 * @param {string} name             directory basename
 * @param {string|null} parentTag   tag inherited from the parent
 * @param {boolean} parentIsProject whether the parent holds a project marker
 * @returns {string|null}
 */
function tagDirectory(name, parentTag, parentIsProject = false) {
  if (parentTag) return parentTag;

  const lower = name.toLowerCase();
  if (isUserDataDirName(lower)) return 'userdata';
  const tag = DIR_TAGS.get(lower);
  if (tag) return tag;

  if (parentIsProject && BUILD_DIR_NAMES.has(lower)) return 'buildoutput';
  return null;
}

