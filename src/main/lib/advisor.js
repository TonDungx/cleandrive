/**
 * Collects advice across a scan: totals per category plus the biggest
 * offenders in each, capped so a huge scan cannot exhaust memory.
 */
class Advisor {
  constructor({ now = Date.now(), keepPerCategory = 100 } = {}) {
    this.now = now;
    this.keep = keepPerCategory;
    this.buckets = new Map();
    this.protectedPaths = [];
    this.appFolders = [];
    this.appFolderKeys = new Set();
  }

  /** Record a folder whose contents are excluded from cleanup advice. */
  addAppFolder(dirPath, reason) {
    const key = dirPath.toLowerCase();
    if (this.appFolderKeys.has(key) || this.appFolders.length >= 200) return;
    this.appFolderKeys.add(key);
    this.appFolders.push({ path: dirPath, name: path.basename(dirPath), reason });
  }

  /**
   * @param {object} file
   * @param {string|null} dirTag
   * @param {boolean} blocked  inside an installed application or roaming app
   *   data, where nothing may be called "safe" no matter what it is named
   * @returns {object|null} the advice recorded, if any
   */
  add(file, dirTag, blockKind = 'none') {
    const result = classifyFile(file, dirTag, this.now, blockKind);
    if (!result) return null;

    let bucket = this.buckets.get(result.category);
    if (!bucket) {
      bucket = { category: result.category, bytes: 0, count: 0, files: [], overflow: false };
      this.buckets.set(result.category, bucket);
    }

    bucket.bytes += file.size;
    bucket.count++;
    bucket.files.push({
      path: file.path,
      size: file.size,
      mtimeMs: file.mtimeMs,
      atimeMs: file.atimeMs,
      reason: result.reason,
      // Which rule decided -- the folder, the extension, the name or the size.
      // The analyzer turns it into a confidence: a folder called Temp is
      // stronger evidence than a file that happens to end in .bak.
      source: result.source,
    });

    // Keep only the largest few; trim in batches rather than on every push.
    if (bucket.files.length >= this.keep * 4) this.trim(bucket);
    return result;
  }

  /** Record a location that was skipped because deleting it is not allowed. */
  addProtected(dirPath, reason) {
    if (this.protectedPaths.length < 200) {
      this.protectedPaths.push({ path: dirPath, name: path.basename(dirPath), reason });
    }
  }

  trim(bucket) {
    bucket.files.sort((a, b) => b.size - a.size);
    if (bucket.files.length > this.keep) {
      bucket.overflow = true;
      bucket.files.length = this.keep;
    }
  }

  /** Final report, sorted safe-first then by size reclaimed. */
  summary() {
    const groups = [...this.buckets.values()].map((bucket) => {
      this.trim(bucket);
      const meta = CATEGORIES[bucket.category];
      return {
        category: bucket.category,
        label: meta.label,
        hint: meta.hint,
        verdict: meta.verdict,
        bytes: bucket.bytes,
        count: bucket.count,
        files: bucket.files,
        truncated: bucket.overflow,
      };
    });

    groups.sort(
      (a, b) => VERDICT_ORDER[a.verdict] - VERDICT_ORDER[b.verdict] || b.bytes - a.bytes
    );

    const total = (verdict) =>
      groups.filter((g) => g.verdict === verdict).reduce((n, g) => n + g.bytes, 0);

    return {
      groups,
      safeBytes: total('safe'),
      reviewBytes: total('review'),
      protectedPaths: this.protectedPaths,
      appFolders: this.appFolders,
    };
  }
}

