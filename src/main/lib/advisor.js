'use strict';

/**
 * Deletion advice.
 *
 * Every file the scanner sees gets one verdict:
 *
 *   safe      regenerable junk -- deleting it costs nothing but disk churn
 *   review    big or long-untouched -- plausibly deletable, but only you know
 *   protected refused by the delete guards; shown so you know why
 *   keep      everything else (default). Never suggested for deletion.
 *
 * Classification has to run on every file of a 500k-file scan, so the
 * expensive part -- deciding what a directory *is* -- happens once per
 * directory and is inherited by everything beneath it. Per file the work is an
 * extension lookup and at most two string tests.
 */

const path = require('node:path');
const { isProtectedPath, extOf } = require('./util');
const { message: m } = require('../../i18n');

const DAY = 24 * 60 * 60 * 1000;

const THRESHOLDS = {
  staleDays: 180, // "you have not opened this in half a year"
  largeBytes: 100 * 1024 * 1024, // 100 MB before a file is worth reviewing
  installerDays: 30, // an installer older than this has served its purpose
  logDays: 7, // keep recent logs, they may still be useful
  archiveBytes: 50 * 1024 * 1024,
};

