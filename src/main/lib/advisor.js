/**
 * Dependency and runtime trees. Two projects each holding their own copy of the
 * same library is normal and correct -- the copies are not redundant, they are
 * per-environment. Deleting one breaks that environment.
 */
const DEPENDENCY_DIRS = new Set([
  'site-packages',
  'dist-packages',
  'node_modules',
  'venv',
  '.venv',
  'virtualenv',
  '.tox',
  'conda-meta',
  'vendor',
  'packages',
  'gems',
  'bower_components',
  'jspm_packages',
  '.gradle',
  '.nuget',
  '.cargo',
  'wheels',
]);

/**
 * Binaries loaded by other programs. Two copies almost always both matter --
 * each one is resolved from a different application's own directory.
 */
const BINARY_MODULE_EXT = new Set([
  'dll', 'pyd', 'so', 'dylib', 'sys', 'ocx', 'drv', 'ax', 'cpl',
  'node', 'jar', 'winmd', 'tlb', 'manifest', 'cat',
]);

/**
 * Why deleting this file is likely to break something, or null if it looks
 * like ordinary user data.
 *
 * Used by the duplicate finder: such files are still listed, but they are never
 * auto-selected by "select all but the oldest copy", because for program
 * components "duplicate" does not mean "redundant".
 *
 * @returns {string|null}
 */
function programComponentReason(filePath) {
  const segments = filePath.split(/[\\/]/);

  // Skip the filename itself; only directories carry this meaning.
  for (let i = 0; i < segments.length - 1; i++) {
    const segment = segments[i].toLowerCase();
    if (DEPENDENCY_DIRS.has(segment)) {
      return m('reason.dependency', 'Inside "{dir}" — each project needs its own copy of this', {
        dir: segments[i],
      });
    }
  }

  if (isProtectedPath(filePath)) {
    return m('reason.systemOwned', 'Belongs to the operating system or an installed program');
  }

  const ext = extOf(segments[segments.length - 1] || '');
  if (BINARY_MODULE_EXT.has(ext)) {
    return m('reason.binaryModule', 'A .{ext} loaded by some program — the copies are usually not interchangeable', {
      ext,
    });
  }

  return null;
}

